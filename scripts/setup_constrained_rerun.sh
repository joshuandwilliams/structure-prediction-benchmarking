#!/bin/bash
# ─────────────────────────────────────────────────────────────────────────────
# setup_constrained_rerun.sh
#
# Prepare a clean re-run of BOTH constrained variants (boltz1_constrained and
# boltz2_constrained) for the Tier-1 benchmark targets.
#
# Why this is needed
# ------------------
# Both extractors wrote constraints in the reference PDB's AUTHOR numbering,
# but Boltz renumbers the sequence it is given as 1..N.  For 9IMU the receptor
# is authored 996-1070 and the effector 33-113, so every emitted index pointed
# at a residue Boltz does not have.  Boltz-2 discarded them silently, which is
# why its constrained run was byte identical to the unconstrained one.  Boltz-1
# was equally mis-targeted; its output differing from baseline only showed that
# something changed, not that the restraints landed.
#
# bin/_constraint_geometry.py now emits Boltz token indices, so both variants
# need re-running before anything can be said about constraints in either.
#
# Why a separate directory
# ------------------------
# run_benchmark.slurm.sh hardcodes `-resume`, and NXF_WORK plus the .nextflow
# cache are both derived from the directory the params file sits in.  Re-running
# in place would therefore hit the cache and hand back the same broken results.
# Submitting from a fresh per-target directory gives a fresh work dir and a fresh
# cache, so everything genuinely re-runs.
#
# This script only WRITES the inputs.  It submits nothing.
#
# Usage:
#   bash scripts/setup_constrained_rerun.sh            # all Tier-1
#   bash scripts/setup_constrained_rerun.sh 6G10 5A6W  # named targets
# ─────────────────────────────────────────────────────────────────────────────
set -euo pipefail

REPO_ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
BENCH_DIR="${REPO_ROOT}/experiments/benchmarks"
MANIFEST="${REPO_ROOT}/data/benchmark_complexes.tsv"
SUBDIR="rerun_constrained"
MODELS="boltz1_constrained boltz2_constrained"

if [ "$#" -gt 0 ]; then
    TARGETS="$*"
else
    # Tier 1 from the manifest (column 4 is tier).
    TARGETS="$(awk -F'\t' 'NR>1 && $4==1 {print $1}' "${MANIFEST}" | sort)"
fi

n=0
for pdb in ${TARGETS}; do
    tgt="${BENCH_DIR}/${pdb}"
    if [ ! -f "${tgt}/${pdb}.pdb" ]; then
        echo "  SKIP ${pdb}: no reference at ${tgt}/${pdb}.pdb" >&2
        continue
    fi

    # Carry the chain assignment across from the original params file rather
    # than assuming A/B, so a target with a different convention is not
    # silently mis-run.
    rec="$(awk -F'"' '/^receptor_chain:/ {print $2}' "${tgt}/params.yml")"
    eff="$(awk -F'"' '/^effector_chain:/ {print $2}' "${tgt}/params.yml")"
    if [ -z "${rec}" ] || [ -z "${eff}" ]; then
        echo "  SKIP ${pdb}: could not read chains from ${tgt}/params.yml" >&2
        continue
    fi

    mkdir -p "${tgt}/${SUBDIR}"
    {
        cat <<EOF
# Clean re-run of the constrained variants only.  Generated by
# scripts/setup_constrained_rerun.sh — do not edit by hand.
#
# Separate directory so Nextflow's cache and work dir are fresh; re-running in
# the parent would resume onto results produced with mis-numbered constraints.

project_name: "${pdb}_constrained_rerun"
outdir:       "./${pdb}_constrained_rerun_results"

reference_pdb:   "../${pdb}.pdb"
receptor_chain:  "${rec}"
effector_chain:  "${eff}"

models:
EOF
        for m in ${MODELS}; do echo "  - ${m}"; done
    } > "${tgt}/${SUBDIR}/params.yml"
    echo "  ${pdb}  (chains ${rec}/${eff})  -> ${SUBDIR}/params.yml"
    n=$((n + 1))
done

cat <<EOF

Prepared ${n} target(s).  Nothing has been submitted.

Next:
  1. Sync up:      ./scripts/sync_to_hpc.sh --dry     (then without --dry)
  2. Submit:       bash scripts/submit_constrained_rerun.sh
  3. When done:    bash scripts/verify_constrained_rerun.sh
EOF
